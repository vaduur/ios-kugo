#!/usr/bin/env python3
"""iOS GLI dispatch table (ios-dispatch.txt) -> C table over Mesa's gl* entry points.

usage: gen-dispatch.py ios-dispatch.txt MESA_INCLUDE_DIR NM_OUTPUT OUT.c

Entry i is called as disp[i](rctx, args of the gl function named in slot i).
Each wrapper makes rctx's context current if needed, then calls the Mesa
entry point of the same name, or of the core name without the vendor
suffix. Names in eagl.c's special table use hand-written functions there;
slots without a Mesa function log once and return 0."""
import re
import sys

layout, inc, nmfile, out = sys.argv[1:5]

hdr = open(inc + '/GL/gl.h').read() + open(inc + '/GL/glext.h').read()
protos = {}
for m in re.finditer(r'(?:GLAPI|GL_APICALL)\s+([\w\s\*]+?)\s*(?:GLAPIENTRY|APIENTRY|GL_APIENTRY)\s+(gl\w+)\s*\(([^)]*)\)', hdr):
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
    params = [] if args in ('', 'void') else [a.strip() for a in args.split(',')]
    protos.setdefault(name, (ret, params))

mesa = {l.split()[-1][1:] for l in open(nmfile) if ' T _gl' in l}

# hand-written in eagl.c: slot name -> function there (same signature plus rctx)
special = {n: 'sgl_' + n[2:] for n in (
    'glDeleteObjectARB', 'glGetObjectParameterivARB', 'glGetInfoLogARB', 'glGetAttachedObjectsARB',
    'glGetHandleARB', 'glDiscardFramebufferEXT', 'glGetShaderPrecisionFormatOES',
    'glReleaseShaderCompilerOES', 'glShaderBinaryOES', 'glGetIntegerIndexedv', 'glTexImage2D',
    'glFinishObjectAPPLE', 'glTestObjectAPPLE', 'glFlush', 'glGetString', 'glCompileShaderARB', 'glLinkProgramARB', 'glShaderSourceARB',
    'glDrawArrays', 'glDrawElements', 'glPixelStorei', 'glBindTexture', 'glDeleteTextures', 'glTexSubImage2D', 'glFramebufferTexture2DEXT', 'glTexParameteri', 'glClear', 'glBindFramebufferEXT')}


def split(param):
    """'const GLfloat *v' -> ('const GLfloat *', 'v')"""
    m = re.match(r'(.*?)(\w+)$', param)
    return m.group(1).strip(), m.group(2)


def is_ptr(t):
    return '*' in t or t in ('GLhandleARB', 'GLsync')


def conv(val, src, dst):
    if src == dst:
        return val
    if is_ptr(src) != is_ptr(dst):
        return '(%s)(uintptr_t)(%s)' % (dst, val)
    return '(%s)(%s)' % (dst, val)


slots = {}
for line in open(layout):
    if line.strip():
        i, name = line.split()
        slots[int(i)] = name
n = max(max(slots) + 1, 1036)       # GLEngine's _gliInitDispatchTable size

body, table, unsupported = [], [], []
for i in range(n):
    name = slots.get(i)
    if name in special:
        table.append('(void *)%s' % special[name])
        continue
    target = None
    if name and name in protos:
        core = re.sub(r'(ARB|EXT|OES|APPLE|NV)$', '', name)
        core = {'glCreateShaderObject': 'glCreateShader', 'glCreateProgramObject': 'glCreateProgram',
                'glUseProgramObject': 'glUseProgram', 'glAttachObject': 'glAttachShader',
                'glDetachObject': 'glDetachShader'}.get(core, core)
        for t in (core, name):
            if t in mesa and t in protos:
                target = t
                break
    if target is None:
        table.append('(void *)unsupported_%d' % i)
        body.append('static long unsupported_%d(void) { sgl_unsupported(%d, "%s"); return 0; }' % (i, i, name or '?'))
        unsupported.append(name or '?')
        continue
    ret, params = protos[name]
    tret, tparams = protos[target]
    sp = [split(p) for p in params]
    # rectangle textures are plain 2D ones here (shaders rewritten in eagl.c)
    args = ', '.join(conv('SGL_TGT(%s)' % v if v in ('target', 'textarget') else v, t, split(tp)[0])
                     for (t, v), tp in zip(sp, tparams))
    call = '%s(%s)' % (target, args)
    decl = ', '.join(['void *rctx'] + params)
    if ret == 'void':
        stmt = '%s; SGL_POST(%d);' % (call, i)
    else:
        stmt = '%s r = %s; SGL_POST(%d); return r;' % (ret, conv(call, tret, ret), i)
    body.append('static %s w_%d(%s) { SGL_CUR(rctx); %s }' % (ret, i, decl, stmt))
    table.append('(void *)w_%d' % i)

with open(out, 'w') as f:
    f.write('/* generated by tools/sweetgl/gen-dispatch.py */\n')
    f.write('#include "eagl.h"\n\n')
    f.write('\n'.join(body))
    f.write('\n\nvoid *const sgl_dispatch[%d] = {\n' % n)
    f.write(''.join('\t%s,\n' % t for t in table))
    f.write('};\n\nconst char *const sgl_slot_names[%d] = {\n' % n)
    f.write(''.join('\t"%s",\n' % (slots.get(i) or '?') for i in range(n)))
    f.write('};\n')
print('%d slots, %d unsupported' % (n, len(unsupported)), file=sys.stderr)
